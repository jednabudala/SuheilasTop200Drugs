function profileFor(generic,drugClass,indications,effects){
const genericName=generic.toLowerCase();

let seriousEffects=
'Severe hypersensitivity and clinically significant organ toxicity are possible; specific risks depend on the drug and patient.';

let boxedWarning='';

let contraindications=
'Known serious hypersensitivity to the drug or its ingredients; additional restrictions depend on the specific drug.';

if(/NSAID/.test(drugClass)){
seriousEffects=
'GI ulceration or bleeding, kidney injury, fluid retention, hypertension, myocardial infarction, stroke, severe skin reactions, and anaphylaxis.';

boxedWarning=
'Increased risk of serious cardiovascular thrombotic events and serious GI bleeding, ulceration, or perforation.';

contraindications=
'Do not use for pain surrounding CABG surgery. Avoid with serious NSAID or aspirin allergy, active serious GI bleeding, or during late pregnancy.';
}

else if(/Opioid/.test(drugClass)){
seriousEffects=
'Life-threatening respiratory depression, profound sedation, hypotension, misuse, addiction, overdose, neonatal withdrawal, and serotonin syndrome with certain opioids.';

boxedWarning=
'Risk of addiction, abuse, misuse, life-threatening respiratory depression, accidental ingestion, neonatal opioid withdrawal, and dangerous sedation with benzodiazepines or other CNS depressants.';

contraindications=
'Avoid with significant respiratory depression, acute or severe uncontrolled asthma, or known or suspected gastrointestinal obstruction.';
}

else if(/SSRI|SNRI|Tricyclic|Atypical antidepressant|SARI/.test(drugClass)){
seriousEffects=
'Suicidal thoughts or behavior, serotonin syndrome, abnormal bleeding, severe hyponatremia, mania activation, seizures, and discontinuation symptoms.';

boxedWarning=
'Antidepressants may increase suicidal thoughts and behaviors in children, adolescents, and young adults.';

contraindications=
'Do not combine with MAO inhibitors. Additional cardiac, seizure, glaucoma, or liver-related restrictions depend on the drug.';
}

else if(/Atypical antipsychotic/.test(drugClass)){
seriousEffects=
'Tardive dyskinesia, neuroleptic malignant syndrome, severe metabolic changes, orthostatic hypotension, seizures, leukopenia, and QT changes.';

boxedWarning=
'Increased mortality in older adults with dementia-related psychosis. These drugs are not approved for dementia-related psychosis.';

contraindications=
'Avoid with serious drug hypersensitivity. Use caution with dementia, significant cardiac disease, seizure disorders, or severe metabolic disease.';
}

else if(/Benzodiazepine/.test(drugClass)){
seriousEffects=
'Respiratory depression, profound sedation, falls, cognitive impairment, misuse, dependence, and potentially life-threatening withdrawal seizures.';

boxedWarning=
'Serious risks occur when combined with opioids. Benzodiazepines can also cause abuse, misuse, addiction, physical dependence, and withdrawal.';

contraindications=
'Avoid with severe respiratory insufficiency, sleep apnea, significant hypersensitivity, or acute narrow-angle glaucoma when applicable.';
}

else if(/Stimulant/.test(drugClass)){
seriousEffects=
'Serious cardiovascular events, hypertension, psychiatric symptoms, growth suppression, seizures, priapism, peripheral vasculopathy, misuse, and dependence.';

boxedWarning=
'Stimulants have a high potential for abuse, misuse, and addiction.';

contraindications=
'Do not use with an MAO inhibitor or within 14 days of stopping one. Additional restrictions may include serious cardiovascular disease, severe agitation, glaucoma, or hyperthyroidism.';
}

else if(/Factor Xa inhibitor|Direct thrombin inhibitor|Vitamin K antagonist/.test(drugClass)){
seriousEffects=
'Major or fatal bleeding, spinal or epidural hematoma, and thrombosis if treatment is stopped prematurely.';

boxedWarning=
'Stopping anticoagulant treatment early increases the risk of blood clots. Spinal or epidural hematomas may cause long-term or permanent paralysis.';

contraindications=
'Avoid during active pathological bleeding. Additional restrictions involving artificial heart valves, kidney disease, liver disease, or pregnancy depend on the drug.';
}

else if(/GLP-1 agonist/.test(drugClass)){
seriousEffects=
'Pancreatitis, gallbladder disease, acute kidney injury from dehydration, severe gastrointestinal effects, hypoglycemia when combined with insulin or insulin secretagogues, and hypersensitivity.';

boxedWarning=
'Certain GLP-1 drugs carry a warning for thyroid C-cell tumors based on animal studies.';

contraindications=
'For drugs carrying the thyroid-tumor warning, avoid with a personal or family history of medullary thyroid carcinoma or MEN2. Avoid with serious hypersensitivity or severe gastroparesis.';
}

else if(/SGLT2 inhibitor/.test(drugClass)){
seriousEffects=
'Euglycemic ketoacidosis, severe genital or urinary infections, Fournier gangrene, dehydration, hypotension, acute kidney injury, and hypoglycemia when combined with insulin.';

contraindications=
'Avoid during dialysis or when the specific drug is contraindicated because of severe kidney impairment. Temporarily stop before major surgery or prolonged fasting.';
}

else if(/ACE inhibitor/.test(drugClass)){
seriousEffects=
'Angioedema, severe hypotension, kidney injury, high potassium, and fetal toxicity.';

boxedWarning=
'Can cause fetal injury or death. Discontinue as soon as pregnancy is detected.';

contraindications=
'Avoid during pregnancy, with previous ACE-inhibitor angioedema, hereditary or idiopathic angioedema, or aliskiren use in patients with diabetes.';
}

else if(/^ARB$|ARNI/.test(drugClass)){
seriousEffects=
'Fetal toxicity, hypotension, high potassium, kidney injury, and rare angioedema.';

boxedWarning=
'Can cause fetal injury or death. Discontinue as soon as pregnancy is detected.';

contraindications=
'Avoid during pregnancy and with aliskiren in patients with diabetes. Sacubitril and valsartan must not be used within 36 hours of an ACE inhibitor or in patients with certain histories of angioedema.';
}

else if(/Fluoroquinolone/.test(drugClass)){
seriousEffects=
'Tendon rupture, peripheral neuropathy, disabling central nervous system effects, abnormal blood glucose, QT prolongation, aortic complications, C. difficile infection, and worsening myasthenia gravis.';

boxedWarning=
'May cause disabling and potentially irreversible tendon, nerve, and central nervous system reactions and can worsen myasthenia gravis.';

contraindications=
'Avoid with serious quinolone hypersensitivity or myasthenia gravis. Use caution with aortic aneurysm risk or QT prolongation.';
}

else if(/insulin/i.test(drugClass)){
seriousEffects=
'Severe hypoglycemia, low potassium, serious allergic reactions, weight gain, and fluid retention when combined with thiazolidinediones.';

contraindications=
'Do not administer during an episode of hypoglycemia or after a serious hypersensitivity reaction to the product.';
}

if(/methotrexate/.test(genericName)){
boxedWarning=
'Methotrexate can cause severe or fatal embryo-fetal toxicity, bone-marrow suppression, liver toxicity, lung toxicity, kidney toxicity, gastrointestinal toxicity, and serious infections.';
}

if(/adalimumab|etanercept/.test(genericName)){
boxedWarning=
'Risk of serious infections, including tuberculosis and invasive fungal infections, and an increased malignancy risk in children and adolescents.';

seriousEffects=
'Serious infection, tuberculosis reactivation, malignancy, demyelinating disease, worsening heart failure, cytopenias, lupus-like syndrome, and hepatitis B reactivation.';
}

if(/montelukast/.test(genericName)){
boxedWarning=
'May cause serious neuropsychiatric events, including suicidal thoughts or behavior. Allergic-rhinitis use should generally be reserved for patients who do not respond to alternatives.';
}

if(/metoclopramide/.test(genericName)){
boxedWarning=
'May cause tardive dyskinesia. Risk increases with treatment duration and cumulative dose. Avoid treatment longer than 12 weeks except in rare cases.';
}

if(/lamotrigine/.test(genericName)){
boxedWarning=
'May cause serious skin reactions, including Stevens-Johnson syndrome and toxic epidermal necrolysis. Risk increases with rapid dose escalation or concurrent valproate.';
}

if(/divalproex/.test(genericName)){
boxedWarning=
'Can cause fatal liver toxicity, major fetal harm, and life-threatening pancreatitis.';
}

if(/carbamazepine/.test(genericName)){
boxedWarning=
'Can cause serious dermatologic reactions associated with certain HLA variants, aplastic anemia, and agranulocytosis.';
}

if(/clindamycin/.test(genericName)){
boxedWarning=
'Can cause C. difficile-associated diarrhea and potentially fatal colitis.';
}

if(/isotretinoin/.test(genericName)){
boxedWarning=
'Causes severe embryo-fetal toxicity. Strict pregnancy-prevention and iPLEDGE requirements apply.';
}

if(/levothyroxine|levothyroxine; liothyronine/.test(genericName)){
boxedWarning=
'Thyroid hormones must not be used for obesity or weight loss. Large doses can cause serious or life-threatening toxicity.';
}

const importantNotes=[];

if(boxedWarning){
importantNotes.push(boxedWarning);
}

if(contraindications){
importantNotes.push(`Contraindications / avoid: ${contraindications}`);
}

return{
indication:indications,
adverseEffects:`${effects}. Serious adverse effects: ${seriousEffects}`,
mechanism:mechanismFor(drugClass),
important:importantNotes.join(' ')
};
}

